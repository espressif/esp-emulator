//! Write a virtual part for the esp-emu co-simulation bus.
//!
//! A part is a WebAssembly module that models a component wired to the
//! chip's pins: a button, a sensor, an LED. The emulator, or a page, loads it
//! and calls the functions of `proto/PART_ABI.md`, exchanging the messages of
//! `proto/esp_cosim.proto` through a buffer in the module's memory.
//!
//! This crate is that ABI, done once. A part is a type that implements
//! [`Device`] — the component, which knows nothing about WebAssembly — and
//! one line of [`export_part!`], which exports every `part_*` function and
//! moves the bytes between the buffer and the device:
//!
//! ```ignore
//! use esp_part::prelude::*;
//!
//! #[derive(Default)]
//! struct Led { pin: Option<u32>, lit: bool }
//!
//! impl Device for Led {
//!     const NAME: &'static str = "led";
//!     fn configure(&mut self, config: &PartConfig) { self.pin = config.pins.get("A").copied(); }
//!     fn claims(&self) -> Vec<Claim> { Vec::new() }  // it drives nothing
//!     fn on_pins(&mut self, levels: u64, _now_ns: u64) {
//!         if let Some(pin) = self.pin { self.lit = levels >> pin & 1 == 0; }  // active low
//!     }
//!     fn state(&self) -> Option<State> { Some(State::new().set("lit", self.lit)) }
//! }
//!
//! esp_part::export_part!(Led);
//! ```
//!
//! `cargo build --release --target wasm32-unknown-unknown` of a `cdylib`
//! crate with that in it is the part. The device runs on the host too, so
//! `cargo test` checks it without an emulator.

use std::sync::Mutex;

pub use prost;
use prost::Message;

/// The messages of `proto/esp_cosim.proto`, generated by `build.rs`.
#[allow(clippy::all)]
pub mod proto {
    include!(concat!(env!("OUT_DIR"), "/esp_cosim.v1.rs"));
}

pub use proto::{
    bus_request, claim, emulator_message::Payload, BusOp, BusReply, BusRequest, Claim, EmulatorMessage,
    GpioClaim, GpioDrive, I2cClaim, I2cTransaction, PartConfig, PartState, Register, SpiClaim,
    SpiTransfer,
};

/// What a part's `lib.rs` needs.
pub mod prelude {
    pub use crate::proto::{
        bus_request, claim, BusOp, BusReply, BusRequest, Claim, EmulatorMessage, GpioClaim, GpioDrive,
        I2cClaim, I2cTransaction, PartConfig, Register, SpiClaim, SpiTransfer,
    };
    pub use crate::{drive, drives, set_value, watches, Device, State};
}

/// The claim to drive `pins` (bit N for GPIO N): the emulator refuses them
/// to every other part.
pub fn drives(pins: u64) -> Claim {
    Claim { what: Some(claim::What::Gpio(GpioClaim { drive_pins: pins, watch_pins: 0 })) }
}

/// The claim to be told every transition of `pins`, each at its own time,
/// where a pin nobody watches arrives as its level once a tick. Not
/// exclusive, and a pin the part drives may be watched too.
pub fn watches(pins: u64) -> Claim {
    Claim { what: Some(claim::What::Gpio(GpioClaim { drive_pins: 0, watch_pins: pins })) }
}

/// The component a part models. Each method is one call of
/// `proto/PART_ABI.md`, with the bytes already decoded; the ones a device
/// has no use for are left at their defaults.
pub trait Device: Default {
    /// The part's name, as the emulator and a page see it: `"pushbutton"`,
    /// `"sht31"`. What it sends in its `Register`.
    const NAME: &'static str;

    /// Whether the device is on a bus: `true` on a device that claims an I2C
    /// address or an SPI chip select and implements [`on_bus`](Self::on_bus).
    /// Left `false`, the bus request decoder stays out of the module, which
    /// is a third of a small part; a bus request then gets no answer, and
    /// the host fails the part naming `part_on_bus`.
    const ON_BUS: bool = false;

    /// Where the board wired the part, by the part's own pin names, and what
    /// it strapped: `config.pins.get("A")`, `config.addr`. Called once,
    /// before anything else, and never again.
    fn configure(&mut self, config: &PartConfig);

    /// What the part answers for: the pins it drives (`drives`), the I2C
    /// address or the SPI chip select it is, on the pins the board wired;
    /// and the pins it wants every transition of (`watches`). The emulator
    /// refuses a claim another part holds, so two parts cannot fight over
    /// one line. See `Register.claims` in `proto/esp_cosim.proto`.
    fn claims(&self) -> Vec<Claim>;

    /// Every pin's level, bit N for GPIO N, after the handshake, after a chip
    /// reset and whenever a pin moves: at each transition of a pin the part
    /// `watches`, once a tick for any other. A part that drives and never
    /// reads leaves this out.
    fn on_pins(&mut self, _levels: u64, _now_ns: u64) {}

    /// What to tell the emulator now, if anything: a pin to drive, usually
    /// ([`drive`]). Asked after every frame and every interaction, with the
    /// emulated time. A device that acts later waits for `now_ns` to reach
    /// its moment, or speaks now with a later `sim_time_ns` and lets the
    /// emulator schedule it (`proto/PART_ABI.md`, "Two ways to act at a time").
    fn poll(&mut self, _now_ns: u64) -> Option<EmulatorMessage> {
        None
    }

    /// A transaction on the bus the part claimed: an I2C transaction or an
    /// SPI transfer to it. The reply must quote `request.correlation_id` and
    /// name its bus (`BusOp`). `None` answers nothing, which is right for an
    /// SPI transfer that reads nothing and a failure for anything else: the
    /// chip is stopped waiting on it.
    fn on_bus(&mut self, _request: &BusRequest) -> Option<BusReply> {
        None
    }

    /// Somebody interacted with the part: `"press"`, `"warmer"`,
    /// `"set:temperature=30.5"` ([`set_value`]). The names are the part's
    /// own; one it does not have is ignored. Not told the time: a device
    /// that acts later notes it here and starts the clock in `poll`.
    fn on_input(&mut self, _name: &str) {}

    /// What the part shows, for a page or a script looking at it: named
    /// values in the part's own words. `None` for a part with nothing to
    /// show.
    fn state(&self) -> Option<State> {
        None
    }
}

/// What a part shows (`part_state`): named values, each the plain decimal or
/// word the part would print.
#[derive(Default, Debug, Clone, PartialEq)]
pub struct State(PartState);

impl State {
    pub fn new() -> Self {
        Self::default()
    }

    /// Add a value under `name`, replacing one already there.
    pub fn set(mut self, name: &str, value: impl ToString) -> Self {
        self.0.values.insert(name.to_string(), value.to_string());
        self
    }

    /// The value shown under `name`.
    pub fn get(&self, name: &str) -> Option<&str> {
        self.0.values.get(name).map(String::as_str)
    }
}

/// A `GpioDrive` of `pin` to `level` at `at_ns`, as [`Device::poll`] returns
/// it. Stamped with the time `poll` was given, it lands now.
pub fn drive(pin: u32, level: bool, at_ns: u64) -> EmulatorMessage {
    EmulatorMessage { sim_time_ns: at_ns, payload: Some(Payload::GpioDrive(GpioDrive { pin, level })) }
}

/// `set:<name>=<value>`, the interaction that puts an exact value in one
/// step: `<name>` lowercase letters, digits and `-`, `<value>` a plain
/// decimal (an optional `-` and fraction, no exponent). Anything else is not
/// a set, and a part ignores it as it does any name it lacks.
pub fn set_value(input: &str) -> Option<(&str, f64)> {
    let (name, value) = input.strip_prefix("set:")?.split_once('=')?;
    let slug = !name.is_empty() && name.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-');
    let digits = value.strip_prefix('-').unwrap_or(value);
    let (whole, frac) = digits.split_once('.').unwrap_or((digits, "0"));
    let plain = |d: &str| !d.is_empty() && d.bytes().all(|b| b.is_ascii_digit());
    if !slug || !plain(whole) || !plain(frac) {
        return None;
    }
    value.parse::<f64>().ok().filter(|n| n.is_finite()).map(|n| (name, n))
}

/// The part as a host sees it: the device, and the buffer the two sides
/// exchange bytes through. [`export_part!`] holds one in a static and calls
/// these from the exported functions; a test can drive one directly.
pub struct Part<D: Device, const N: usize> {
    pub buffer: [u8; N],
    pub device: D,
}

impl<D: Device, const N: usize> Default for Part<D, N> {
    fn default() -> Self {
        Self { buffer: [0; N], device: D::default() }
    }
}

impl<D: Device, const N: usize> Part<D, N> {
    /// Encode `msg` into the buffer and return its length. A message that
    /// does not fit is the device's bug, and a trap names the part.
    pub fn write(&mut self, msg: &impl Message) -> i32 {
        let len = msg.encoded_len();
        assert!(len <= N, "{}: a {len}-byte message does not fit its {N}-byte buffer", D::NAME);
        let mut free = &mut self.buffer[..];
        msg.encode(&mut free).expect("checked to fit");
        len as i32
    }

    /// The first `len` bytes of the buffer, as a host wrote them. A length
    /// the buffer does not hold is the host's bad frame, taken like one that
    /// does not decode: ignored, never a trap pinned on the device.
    fn frame(buffer: &[u8], len: i32) -> &[u8] {
        usize::try_from(len).ok().and_then(|n| buffer.get(..n)).unwrap_or(&[])
    }

    /// `part_configure`: the first `len` bytes of the buffer are a
    /// `PartConfig`. One that does not decode leaves the device unwired.
    pub fn configure(&mut self, len: i32) {
        if let Ok(config) = PartConfig::decode(Self::frame(&self.buffer, len)) {
            self.device.configure(&config);
        }
    }

    /// `part_register`.
    pub fn register(&mut self) -> i32 {
        let reg = Register {
            proto_version: proto::ProtoVersion::Current as u32,
            name: D::NAME.into(),
            claims: self.device.claims(),
        };
        self.write(&reg)
    }

    /// `part_on_bus`: the first `len` bytes are a `BusRequest`. One that does
    /// not decode comes from a host speaking another contract: nothing is
    /// returned, and the host reports the part as failed.
    pub fn on_bus(&mut self, len: i32) -> i32 {
        if !D::ON_BUS {
            return 0;
        }
        let Ok(request) = BusRequest::decode(Self::frame(&self.buffer, len)) else { return 0 };
        match self.device.on_bus(&request) {
            Some(reply) => self.write(&reply),
            None => 0,
        }
    }

    /// `part_poll`.
    pub fn poll(&mut self, now_ns: u64) -> i32 {
        match self.device.poll(now_ns) {
            Some(msg) => self.write(&msg),
            None => 0,
        }
    }

    /// `part_on_input`: the first `len` bytes are the interaction's name.
    pub fn on_input(&mut self, len: i32) {
        if let Ok(name) = std::str::from_utf8(Self::frame(&self.buffer, len)) {
            self.device.on_input(name);
        }
    }

    /// `part_state`.
    pub fn state(&mut self) -> i32 {
        match self.device.state() {
            Some(State(state)) => self.write(&state),
            None => 0,
        }
    }
}

/// The static one part holds: a host instantiates the module once per placed
/// part. Made on first use, so the device needs no `const fn`.
pub struct Slot<D: Device, const N: usize>(Mutex<Option<Part<D, N>>>);

impl<D: Device, const N: usize> Default for Slot<D, N> {
    fn default() -> Self {
        Self::new()
    }
}

impl<D: Device, const N: usize> Slot<D, N> {
    pub const fn new() -> Self {
        Self(Mutex::new(None))
    }

    /// The part, made on the first call.
    pub fn with<R>(&self, f: impl FnOnce(&mut Part<D, N>) -> R) -> R {
        let mut slot = self.0.lock().unwrap_or_else(|e| e.into_inner());
        f(slot.get_or_insert_with(Part::default))
    }
}

/// Export `$device` as a part: every function of `proto/PART_ABI.md`, over
/// a buffer of `$buffer` bytes (512 if left out).
///
/// ```ignore
/// esp_part::export_part!(PushButton);
/// esp_part::export_part!(Sht31, buffer = 1024);
/// ```
///
/// The buffer holds every message either side passes: a bus request with a
/// long write needs more than a button's drives. A host hands over nothing
/// that does not fit, and a `BusRequest` that does not fit fails the part.
#[macro_export]
macro_rules! export_part {
    ($device:ty) => {
        $crate::export_part!($device, buffer = 512);
    };
    ($device:ty, buffer = $n:expr) => {
        static __ESP_PART: $crate::Slot<$device, $n> = $crate::Slot::new();

        #[no_mangle]
        pub extern "C" fn part_abi_version() -> i32 {
            $crate::proto::PartAbiVersion::Current as i32
        }
        #[no_mangle]
        pub extern "C" fn part_buffer() -> i32 {
            __ESP_PART.with(|p| p.buffer.as_ptr() as i32)
        }
        #[no_mangle]
        pub extern "C" fn part_buffer_len() -> i32 {
            $n
        }
        #[no_mangle]
        pub extern "C" fn part_configure(len: i32) {
            __ESP_PART.with(|p| p.configure(len))
        }
        #[no_mangle]
        pub extern "C" fn part_register() -> i32 {
            __ESP_PART.with(|p| p.register())
        }
        #[no_mangle]
        pub extern "C" fn part_on_pins(levels: u64, now_ns: u64) {
            __ESP_PART.with(|p| p.device.on_pins(levels, now_ns))
        }
        #[no_mangle]
        pub extern "C" fn part_on_bus(len: i32) -> i32 {
            __ESP_PART.with(|p| p.on_bus(len))
        }
        #[no_mangle]
        pub extern "C" fn part_poll(now_ns: u64) -> i32 {
            __ESP_PART.with(|p| p.poll(now_ns))
        }
        #[no_mangle]
        pub extern "C" fn part_on_input(len: i32) {
            __ESP_PART.with(|p| p.on_input(len))
        }
        #[no_mangle]
        pub extern "C" fn part_state() -> i32 {
            __ESP_PART.with(|p| p.state())
        }
    };
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A button: drives its pin low while pressed.
    #[derive(Default)]
    struct Button {
        pin: Option<u32>,
        down: bool,
        reported: bool,
    }

    impl Device for Button {
        const NAME: &'static str = "button";
        fn configure(&mut self, config: &PartConfig) {
            self.pin = config.pins.get("A").copied();
        }
        fn claims(&self) -> Vec<Claim> {
            self.pin.map(|p| drives(1 << p)).into_iter().collect()
        }
        fn poll(&mut self, now_ns: u64) -> Option<EmulatorMessage> {
            if self.down == self.reported {
                return None;
            }
            self.reported = self.down;
            Some(drive(self.pin?, !self.down, now_ns))
        }
        fn on_input(&mut self, name: &str) {
            self.down = name == "press";
        }
        fn state(&self) -> Option<State> {
            Some(State::new().set("pressed", self.down))
        }
    }

    fn part() -> Part<Button, 64> {
        let mut part = Part::<Button, 64>::default();
        let cfg = PartConfig { pins: [("A".to_string(), 9)].into(), addr: 0 }.encode_to_vec();
        part.buffer[..cfg.len()].copy_from_slice(&cfg);
        part.configure(cfg.len() as i32);
        part
    }

    #[test]
    fn the_register_names_the_device_and_carries_its_claims() {
        let mut part = part();
        let n = part.register() as usize;
        let reg = Register::decode(&part.buffer[..n]).unwrap();
        assert_eq!(reg.name, "button");
        assert_eq!(reg.proto_version, proto::ProtoVersion::Current as u32);
        assert_eq!(reg.claims, [drives(1 << 9)]);
    }

    #[test]
    fn an_input_arrives_as_its_name_and_a_poll_writes_what_the_device_says() {
        let mut part = part();
        part.buffer[..5].copy_from_slice(b"press");
        part.on_input(5);
        let n = part.poll(1_000) as usize;
        assert_eq!(EmulatorMessage::decode(&part.buffer[..n]).unwrap(), drive(9, false, 1_000));
        assert_eq!(part.poll(2_000), 0, "nothing new");
    }

    #[test]
    fn the_state_is_what_the_device_shows_and_zero_for_a_device_showing_nothing() {
        let mut part = part();
        let n = part.state() as usize;
        let shown = PartState::decode(&part.buffer[..n]).unwrap();
        assert_eq!(shown.values.get("pressed").map(String::as_str), Some("false"));

        #[derive(Default)]
        struct Mute;
        impl Device for Mute {
            const NAME: &'static str = "mute";
            fn configure(&mut self, _: &PartConfig) {}
            fn claims(&self) -> Vec<Claim> {
                Vec::new()
            }
        }
        assert_eq!(Part::<Mute, 64>::default().state(), 0);
        assert_eq!(Part::<Mute, 64>::default().on_bus(0), 0, "a device without a bus answers nothing");
    }

    #[test]
    fn a_device_on_a_bus_answers_and_one_that_is_not_does_not() {
        #[derive(Default)]
        struct Echo;
        impl Device for Echo {
            const NAME: &'static str = "echo";
            const ON_BUS: bool = true;
            fn configure(&mut self, _: &PartConfig) {}
            fn claims(&self) -> Vec<Claim> {
                Vec::new()
            }
            fn on_bus(&mut self, r: &BusRequest) -> Option<BusReply> {
                Some(BusReply { correlation_id: r.correlation_id, ack: true, data: vec![1], op: BusOp::I2c as i32 })
            }
        }
        let req = BusRequest { correlation_id: 5, op: None }.encode_to_vec();
        let mut part = Part::<Echo, 64>::default();
        part.buffer[..req.len()].copy_from_slice(&req);
        let n = part.on_bus(req.len() as i32) as usize;
        assert_eq!(BusReply::decode(&part.buffer[..n]).unwrap().correlation_id, 5);

        // The same device with ON_BUS left false is not asked.
        #[derive(Default)]
        struct Deaf;
        impl Device for Deaf {
            const NAME: &'static str = "deaf";
            fn configure(&mut self, _: &PartConfig) {}
            fn claims(&self) -> Vec<Claim> {
                Vec::new()
            }
            fn on_bus(&mut self, _: &BusRequest) -> Option<BusReply> {
                panic!("not asked")
            }
        }
        let mut part = Part::<Deaf, 64>::default();
        part.buffer[..req.len()].copy_from_slice(&req);
        assert_eq!(part.on_bus(req.len() as i32), 0);
    }

    #[test]
    fn a_config_that_does_not_decode_leaves_the_device_unwired() {
        let mut part = Part::<Button, 64>::default();
        part.buffer[..3].copy_from_slice(&[0xFF, 0xFF, 0xFF]);
        part.configure(3);
        assert!(part.device.pin.is_none());
    }

    #[test]
    #[should_panic(expected = "does not fit")]
    fn a_message_longer_than_the_buffer_traps_rather_than_overruns() {
        let mut part = Part::<Button, 8>::default();
        part.write(&Register { name: "a name longer than eight bytes".into(), ..Default::default() });
    }

    #[test]
    fn set_value_takes_a_plain_decimal_and_nothing_else() {
        assert_eq!(set_value("set:temperature=30.5"), Some(("temperature", 30.5)));
        assert_eq!(set_value("set:rh-2=-7"), Some(("rh-2", -7.0)));
        for odd in ["set:t=1e2", "set:t=", "set:t=.5", "set:t=5.", "set:T=5", "set:t", "press", "set:=5"] {
            assert_eq!(set_value(odd), None, "{odd}");
        }
    }
}
